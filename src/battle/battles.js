// 战役结算判定：胜利 / 存活 / 爆仓
export function judgeBattle(battle, finalBalance, blown) {
  const pnl = finalBalance - battle.capital;
  if (blown || finalBalance <= battle.capital * 0.2) return { win: false, grade: '爆仓', pnl };
  if (pnl >= battle.capital * battle.winPct) return { win: true, grade: '胜利', pnl };
  return { win: false, grade: '存活', pnl };
}
